/** @returns {{ major: string, minor: string|null }} 중분류명과(있으면) 소분류명 */
export function industryName(code) {
  if (!code) return { major: "업종 정보 없음", minor: null };
  const c = String(code);
  return { major: KSIC2[c.slice(0, 2)] || `업종코드 ${c}`, minor: KSIC3[c.slice(0, 3)] || null };
}

// 금융업(64~66)은 매출·영업이익 구조가 달라 일부 비율이 의미가 없다.
export function isFinancial(code) {
  return /^6[4-6]/.test(String(code || ""));
}
